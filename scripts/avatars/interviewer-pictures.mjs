// Lists the interviewer pictures in public/interviewers/ (<id>.webp, .jpg or .png) and writes
// lib/interviewers/pictures.ts, so the catalog knows which pictures exist without reading the disk at
// runtime (the catalog is also used in the browser). Runs before `dev` and `build`; run it by hand
// after adding pictures: `node scripts/avatars/interviewer-pictures.mjs`.
import { readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../../public/interviewers/", import.meta.url);
const files = readdirSync(dir)
  .filter((f) => /^[a-z0-9-]+\.(webp|jpe?g|png)$/.test(f))
  .sort();
const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.[^.]+$/, ""))}: ${JSON.stringify(`/interviewers/${f}`)},`);
writeFileSync(
  new URL("../../lib/interviewers/pictures.ts", import.meta.url),
  `// Generated by scripts/avatars/interviewer-pictures.mjs from public/interviewers/: do not edit by hand.\n\nexport const PICTURES: Record<string, string> = {\n${entries.join("\n")}${entries.length ? "\n" : ""}};\n`,
);
console.log(`interviewer pictures: ${files.length}`);
